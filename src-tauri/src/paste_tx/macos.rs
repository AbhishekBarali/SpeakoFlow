//! macOS clipboard transaction (see `paste_tx`). Mirrors Handy's
//! `paste_tx/macos.rs`; it cannot be compiled on the Windows machine this was
//! ported on, so changes here need a Mac build.
//!
//! `declareTypes:owner:` puts a *promise* on the general pasteboard instead of
//! data. When a consumer asks for the text, AppKit calls
//! `pasteboard:provideDataForType:` on the owner object, which is the read
//! receipt. The previous clipboard is put back once the reads go quiet
//! (`paste_tx::evaluate`), guarded by the pasteboard `changeCount` so a newer
//! copy by the user is never overwritten.
//!
//! Threading: publishing and the keystroke happen on the calling (main)
//! thread, because AppKit answers a promise on the main run loop; the paste
//! returns right after the keystroke, which frees that loop. The wait runs on
//! a worker thread, and the restore is dispatched back to the main thread.
//!
//! objc2 comes through `tauri_nspanel`'s re-exports, the same copy
//! `commands/assistant.rs` uses, so no dependency is added for this.

use std::sync::{Arc, Mutex, MutexGuard};
use std::thread;
use std::time::{Duration, Instant};

use log::{error, info, warn};
use tauri::AppHandle;
use tauri_nspanel::objc2::rc::Retained;
use tauri_nspanel::objc2::{define_class, msg_send, AnyThread, DefinedClass, MainThreadMarker};
use tauri_nspanel::objc2_app_kit::{NSPasteboard, NSPasteboardTypeString};
use tauri_nspanel::objc2_foundation::{NSArray, NSInteger, NSObject, NSString};
use tauri_plugin_clipboard_manager::ClipboardExt;

use super::{
    evaluate, send_auto_submit_later, send_chord, settle_reason, settlement, ClipboardSettle,
    PasteRequest, PasteTxError, TxState, WaitDecision,
};
use crate::settings::AutoSubmitKey;

/// Marker types declared with the text so well-behaved clipboard managers
/// (Maccy, Paste, ...) skip the dictation, the macOS counterpart of the
/// Windows history opt-out. Fewer eager readers also means a receipt is more
/// likely to be the target. Conventions only; nothing enforces them.
const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

/// How often the waiter checks the transaction.
const POLL: Duration = Duration::from_millis(15);

pub struct ProviderIvars {
    state: Arc<Mutex<TxState>>,
    text: String,
    /// An assistant answer's HTML, promised as `public.html` beside the text.
    html: Option<String>,
}

/// The pasteboard type an answer's HTML is promised under.
const HTML_TYPE: &str = "public.html";

define_class!(
    // SAFETY: NSObject has no subclassing requirements and the ivars are
    // plain Rust values guarded by a Mutex.
    #[unsafe(super(NSObject))]
    #[name = "SpeakoFlowPasteProvider"]
    #[ivars = ProviderIvars]
    pub struct SpeakoFlowPasteProvider;

    impl SpeakoFlowPasteProvider {
        // NSPasteboardOwner informal protocol: the pasteboard asks for the
        // promised data, which is the receipt that a consumer read it.
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            // SAFETY: NSPasteboardTypeString is a read-only framework static.
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            let html = ivars
                .html
                .as_deref()
                .filter(|_| data_type.isEqualToString(&NSString::from_str(HTML_TYPE)));
            // Only a text or HTML read is a receipt (rich editors read the
            // HTML of an answer, never its text): a request for a marker type
            // is a clipboard manager inspecting the markers, not the target.
            if is_text || html.is_some() {
                lock(&ivars.state).record_receipt(Instant::now());
            }
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else if let Some(html) = html {
                NSString::from_str(html)
            } else {
                NSString::from_str("")
            };
            let _ = pasteboard.setString_forType(&payload, data_type);
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            lock(&self.ivars().state).ownership_lost = true;
        }
    }
);

impl SpeakoFlowPasteProvider {
    fn new(state: Arc<Mutex<TxState>>, text: String, html: Option<String>) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { state, text, html });
        unsafe { msg_send![super(this), init] }
    }
}

struct MacPending {
    state: Arc<Mutex<TxState>>,
    saved_text: Option<String>,
    saved_image: Option<tauri::image::Image<'static>>,
    change_count: NSInteger,
    provider: Option<Retained<SpeakoFlowPasteProvider>>,
    auto_submit: Option<AutoSubmitKey>,
    /// "Copy to clipboard": left as ordinary text when settling.
    leave_copy: Option<String>,
    settled: bool,
}

/// The transaction holding the clipboard right now, if any. A new paste
/// settles it first, so its snapshot is the user's content.
static PENDING: Mutex<Option<Arc<Mutex<MacPending>>>> = Mutex::new(None);

fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex.lock().unwrap_or_else(|e| e.into_inner())
}

/// Settle a transaction once: restore the previous clipboard (or leave the
/// copy) while it is still ours, and send an owed auto-submit unless
/// `send_submit` is false. Main thread only. `enigo` is the input already
/// locked by a paste in progress; without it the lock is taken briefly.
fn settle(
    pending: &Arc<Mutex<MacPending>>,
    app_handle: &AppHandle,
    enigo: Option<&mut enigo::Enigo>,
    send_submit: bool,
) {
    let mut p = lock(pending);
    if p.settled {
        return;
    }
    p.settled = true;

    let still_ours = NSPasteboard::generalPasteboard().changeCount() == p.change_count;
    let (decision, reason) = {
        let state = lock(&p.state);
        (
            settlement(
                &state,
                still_ours,
                p.auto_submit.is_some(),
                p.leave_copy.is_some(),
            ),
            settle_reason(&state),
        )
    };
    info!("Paste: settling, {reason}");

    if let (true, Some(key)) = (decision.submit, p.auto_submit) {
        if !send_submit {
            warn!(
                "Paste: skipped the previous dictation's auto-submit; an ask started \
                 before its target had read it"
            );
        } else {
            match enigo {
                Some(enigo) => {
                    if let Err(e) = crate::clipboard::send_return_key(enigo, key) {
                        warn!("Paste: could not send the auto-submit key: {e}");
                    }
                }
                None => send_auto_submit_later(app_handle, key),
            }
        }
    }

    let clipboard = app_handle.clipboard();
    match decision.clipboard {
        ClipboardSettle::Untouched => {
            info!("Paste: the clipboard changed since the paste; leaving it as it is")
        }
        ClipboardSettle::LeaveCopy => {
            if let Some(copy) = &p.leave_copy {
                let _ = clipboard.write_text(copy);
            }
        }
        ClipboardSettle::Restore => {
            if let Some(text) = &p.saved_text {
                let _ = clipboard.write_text(text);
            } else if let Some(image) = &p.saved_image {
                let _ = clipboard.write_image(image);
            } else {
                let _ = clipboard.clear();
            }
        }
    }

    // Release the owner; any promise still out dies with the contents just
    // replaced (or with the external change).
    p.provider = None;
}

/// Settle the previous transaction, if one still holds the clipboard, so the
/// caller's snapshot is the user's content.
fn flush_pending(app_handle: &AppHandle, enigo: &mut enigo::Enigo) {
    let previous = lock(&PENDING).take();
    if let Some(previous) = previous {
        lock(&lock(&previous).state).cancelled = true;
        settle(&previous, app_handle, Some(enigo), true);
    }
}

/// How long a caller off the main thread waits for the main thread to settle
/// a pending paste. AppKit answers a promise on the main run loop, which is
/// free between pastes, so this normally takes a few milliseconds.
const SETTLE_WAIT: Duration = Duration::from_millis(300);

/// Settle the pending transaction, if any, on the main thread, and wait for
/// it (briefly). Tauri runs `run_on_main_thread` at once when called on the
/// main thread, so this works from either.
fn settle_on_main(app_handle: &AppHandle, send_submit: bool) {
    if lock(&PENDING).is_none() {
        return;
    }
    let (done, settled) = std::sync::mpsc::channel();
    let app = app_handle.clone();
    let queued = app_handle.run_on_main_thread(move || {
        let previous = lock(&PENDING).take();
        if let Some(previous) = previous {
            lock(&lock(&previous).state).cancelled = true;
            settle(&previous, &app, None, send_submit);
        }
        let _ = done.send(());
    });
    if queued.is_err() || settled.recv_timeout(SETTLE_WAIT).is_err() {
        warn!("Paste: could not settle the pending paste in time");
    }
}

/// See `paste_tx::settle_pending`: before an ask's selection harvest, whose
/// keys are held, so an owed Enter is dropped.
pub(super) fn settle_pending(app_handle: &AppHandle) {
    settle_on_main(app_handle, false);
}

/// See `paste_tx::settle_before_exit`.
pub(super) fn settle_before_exit(app_handle: &AppHandle) {
    settle_on_main(app_handle, true);
}

fn spawn_waiter(pending: Arc<Mutex<MacPending>>, app_handle: AppHandle) {
    thread::spawn(move || {
        loop {
            thread::sleep(POLL);
            let p = lock(&pending);
            if p.settled {
                // A newer paste settled this one already.
                return;
            }
            let decision = evaluate(&lock(&p.state), Instant::now());
            drop(p);
            if decision == WaitDecision::Finish {
                break;
            }
        }

        let for_main = pending.clone();
        let app = app_handle.clone();
        let _ = app_handle.run_on_main_thread(move || {
            settle(&for_main, &app, None, true);
            let mut slot = lock(&PENDING);
            if slot
                .as_ref()
                .is_some_and(|current| Arc::ptr_eq(current, &for_main))
            {
                *slot = None;
            }
        });
    });
}

pub(super) fn run(
    app_handle: &AppHandle,
    enigo: &mut enigo::Enigo,
    request: PasteRequest<'_>,
) -> Result<(), PasteTxError> {
    // AppKit answers a promise on the main run loop. Declared from any other
    // thread, the target's read could wait on a thread nobody services and
    // paste nothing, so take the plain paste (which works from any thread)
    // rather than risk it. Dictation and Insert both paste on the main thread.
    if MainThreadMarker::new().is_none() {
        return Err(PasteTxError::Unavailable(
            "not on the main thread".to_string(),
        ));
    }
    flush_pending(app_handle, enigo);

    let clipboard = app_handle.clipboard();
    let saved_text = clipboard.read_text().ok().filter(|t| !t.is_empty());
    // Only probe for an image when there is no text: reading one decodes the
    // whole bitmap (same as the plain paste, Handy #1231).
    let saved_image = if saved_text.is_none() {
        clipboard.read_image().ok().map(|image| image.to_owned())
    } else {
        None
    };

    let state = Arc::new(Mutex::new(TxState::new()));
    let provider = SpeakoFlowPasteProvider::new(
        state.clone(),
        request.text.to_string(),
        request.html.map(super::utf8_html_document),
    );
    let pasteboard = NSPasteboard::generalPasteboard();

    let mut types: Vec<Retained<NSString>> = Vec::with_capacity(2 + CONCEALMENT_TYPES.len());
    types.push(NSString::from_str("public.utf8-plain-text"));
    if request.html.is_some() {
        types.push(NSString::from_str(HTML_TYPE));
    }
    for t in CONCEALMENT_TYPES {
        types.push(NSString::from_str(t));
    }
    let types = NSArray::from_retained_slice(&types);

    // declareTypes:owner: clears the pasteboard and puts the promise on it;
    // it returns the new changeCount.
    let change_count: NSInteger =
        unsafe { msg_send![&*pasteboard, declareTypes: &*types, owner: &*provider] };
    if change_count <= 0 {
        return Err(PasteTxError::Unavailable(
            "declareTypes:owner: failed".to_string(),
        ));
    }
    lock(&state).published_at = Instant::now();

    if !request.paste_delay.is_zero() {
        thread::sleep(request.paste_delay);
    }

    // Marked before sending: the keystroke is held ~100 ms, and a fast target
    // may read while it is still down.
    lock(&state).injected_at = Some(Instant::now());
    let sent = send_chord(enigo, request.paste_method);
    if sent.is_err() {
        lock(&state).injection_failed = true;
    }

    let pending = Arc::new(Mutex::new(MacPending {
        state,
        saved_text,
        saved_image,
        change_count,
        provider: Some(provider),
        auto_submit: request.auto_submit,
        leave_copy: request.leave_on_clipboard,
        settled: false,
    }));
    *lock(&PENDING) = Some(pending.clone());
    spawn_waiter(pending, app_handle.clone());

    sent.map_err(|e| {
        error!("Paste: could not send the paste keystroke: {e}");
        PasteTxError::Keystroke(e)
    })
}
